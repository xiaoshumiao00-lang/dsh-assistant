#!/usr/bin/env python3
"""Generate the full GB2312 character table used by the LVGL fonts.

Why a generated table instead of a hand-written chars.txt:
  the completion screen renders host-supplied Chinese of any kind, so the font
  must carry a whole standard charset, not the 1073 characters we happened to
  type into tools/chars.txt. Python's built-in gb2312 codec gives us the
  authoritative code table without typing thousands of characters by hand.

Outputs (both UTF-8, deterministic):
  tools/chars_gb2312.txt       characters, one header comment + fixed-width lines
  main/font/tihu_charset.h     uint16 code point list for the boot self-test

The head of the table is the explicit ASCII range 0x20..0x7E (added as a range
by lv_font_conv, so it is not repeated in the .txt file), then all 7445 GB2312
characters (682 symbols in rows 1..9, 6763 hanzi in rows 16..87), then a short
supplement of characters that are deliberately outside GB2312 but that people
actually type (龘靐齉 and friends). Everything is filtered against the TTF's
real cmap so the .txt never lists a glyph the font cannot draw.

Usage:
  python tools/gen_charset.py [--font C:\\Windows\\Fonts\\simhei.ttf]
"""
import argparse
import os
import struct
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)

# Characters outside GB2312 that the rare-character screen exercises. Keep the
# list small (each glyph costs ~200 B at 20px/4bpp) and let the font cmap drop
# anything SimHei does not actually have.
RARE_SUPPLEMENT = (
    "龘靐齉爨麤龖犇骉羴猋鑫淼焱垚犇"
    "囧囧槑玊尛嬲嫑烎兲氼嘦勥巭"
    "蒍蓺藄蘡籴粜"
)

# U+00B7 «·»: the UI writes counters as 「完成 · 3/12」. Windows' cp936 table maps
# GB2312 0xA1A4 to U+30FB (・) instead, so the plain codec round-trip loses the
# middle dot the firmware actually prints; add it explicitly.
EXTRA_CHARS = "·"

ASCII_FIRST = 0x20
ASCII_LAST = 0x7E


def gb2312_chars():
    """Every character of GB2312, in code order (rows 1..9, 16..87)."""
    out = []
    for lead in range(0xA1, 0xF8):
        for trail in range(0xA1, 0xFF):
            if trail == 0x7F:
                continue
            try:
                ch = bytes((lead, trail)).decode('gb2312')
            except UnicodeDecodeError:
                continue
            out.append(ch)
    return out


def load_cmap(font_path):
    """Return the set of code points covered by a TTF (cmap formats 4/12)."""
    sys.path.insert(0, HERE)
    try:
        from font_cmap_probe import cmap_set
        return cmap_set(font_path)
    except Exception as exc:  # pragma: no cover - fonts are optional
        print('warning: cannot read %s (%s); keeping every character' % (font_path, exc))
        return None


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--font', default=r'C:\Windows\Fonts\simhei.ttf')
    args = ap.parse_args()

    gb = gb2312_chars()
    hanzi = [ch for ch in gb if 0x4E00 <= ord(ch) <= 0x9FFF]
    symbols = [ch for ch in gb if not 0x4E00 <= ord(ch) <= 0x9FFF]
    print('GB2312 rows parsed: %d total, %d hanzi, %d symbols' % (len(gb), len(hanzi), len(symbols)))

    supplement = []
    for ch in RARE_SUPPLEMENT + EXTRA_CHARS:
        if ch not in gb and ch not in supplement:
            supplement.append(ch)
    print('supplement (outside GB2312): %d' % len(supplement))

    # Never list a character the TTF cannot draw: lv_font_conv would silently
    # skip it, the .c would disagree with the table, and the boot self-test would
    # report a permanent shortfall.
    cmap = load_cmap(args.font) if os.path.exists(args.font) else None
    if cmap is not None:
        dropped_gb = [ch for ch in gb if ord(ch) not in cmap]
        if dropped_gb:
            print('dropped %d GB2312 chars missing from the font (kept out of the table): %s'
                  % (len(dropped_gb), ''.join(dropped_gb)))
        gb = [ch for ch in gb if ord(ch) in cmap]
        before = len(supplement)
        supplement = [ch for ch in supplement if ord(ch) in cmap]
        if len(supplement) != before:
            print('dropped %d supplement chars missing from the font' % (before - len(supplement)))

    chars = gb + supplement

    txt_path = os.path.join(HERE, 'chars_gb2312.txt')
    with open(txt_path, 'w', encoding='utf-8', newline='\n') as fh:
        fh.write('# GB2312 full charset + rare supplement (generated by tools/gen_charset.py)\n')
        fh.write('# ASCII 0x20..0x7E is added as a font range by gen_font_subset.cjs\n')
        fh.write('# %d characters: %d GB2312 (%d hanzi, %d symbols) + %d supplement\n'
                 % (len(chars), len(gb), len(hanzi), len(symbols), len(supplement)))
        for i in range(0, len(chars), 48):
            fh.write(''.join(chars[i:i + 48]) + '\n')
    print('wrote %s (%d chars, %d bytes)' % (txt_path, len(chars), os.path.getsize(txt_path)))

    header_path = os.path.join(ROOT, 'main', 'font', 'tihu_charset.h')
    cps = sorted({ord(ch) for ch in chars})
    with open(header_path, 'w', encoding='utf-8', newline='\n') as fh:
        fh.write('/* Generated by tools/gen_charset.py -- do not edit. */\n')
        fh.write('/* GB2312 full charset (%d chars) + %d rare supplement. */\n'
                 % (len(gb), len(supplement)))
        fh.write('#pragma once\n\n#include <stdint.h>\n\n')
        fh.write('#define TIHU_CHARSET_COUNT %du\n\n' % len(cps))
        fh.write('static const uint16_t tihu_charset_cps[TIHU_CHARSET_COUNT] = {\n')
        for i in range(0, len(cps), 12):
            row = ', '.join('0x%04X' % cp for cp in cps[i:i + 12])
            fh.write('    ' + row + ',\n')
        fh.write('};\n')
    print('wrote %s (%d code points)' % (header_path, len(cps)))


if __name__ == '__main__':
    main()
